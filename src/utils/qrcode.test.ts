test('same QR code as the flyer one, checked on a phone', () => {
  const qr = encodeQr('https://www.serrurerierepublique.fr/offre', 'H');
  assert.equal(qr.version, 5);
  assert.deepEqual(
    qr.modules.map((row) => row.map((v) => (v ? '1' : '0')).join('')),
    FLYER
  );
});

test('longer address grows the version; SVG is well formed', () => {
  const qr = encodeQr('https://www.serrurerierepublique.fr/offre?o=syndics-printemps-2027', 'H');
  assert.ok(qr.version > 5);
  assert.equal(qr.size, qr.version * 4 + 17);
  const svg = qrToSvg(qr);
  assert.ok(svg.startsWith('<svg') && svg.includes('viewBox="0 0 ' + (qr.size + 8)));
});
